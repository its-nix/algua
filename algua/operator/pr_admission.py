"""DRAFT: adopt an existing reviewed PR; never merge or publish main.

The root-controlled descriptor is an explicit owner policy/Task4 attestation,
not evidence generated by this code. Missing configuration always refuses.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path
from typing import Any

from algua.operator.diff_policy import evaluate_diff
from algua.operator.gitops import GitOps


class AdmissionPending(RuntimeError):
    """An operational fence failed; never record an economic promote rejection."""


def _pairs(items: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in items:
        if key in result:
            raise ValueError("duplicate admission field")
        result[key] = value
    return result


def _descriptor() -> dict:
    value = os.environ.get("ALGUA_MERGEBACK_ADMISSION")
    if not value:
        raise ValueError("admission not configured")
    path = Path(value).absolute()
    for part in (path, *path.parents):
        stat = part.lstat()
        if part.is_symlink() or stat.st_uid != 0 or stat.st_mode & 0o022:
            raise ValueError("admission must be root-controlled")
    if not path.is_file():
        raise ValueError("admission must be a regular file")
    with path.open("rb") as stream:
        raw = stream.read(16 * 1024 + 1)
    if len(raw) > 16 * 1024:
        raise ValueError("admission descriptor too large")
    result = json.loads(raw, object_pairs_hook=_pairs)
    if not isinstance(result, dict):
        raise ValueError("invalid admission descriptor")
    return result


def _api(repository: str, suffix: str) -> Any:
    result = subprocess.run(
        ["gh", "api", f"repos/{repository}/{suffix}", "--hostname", "github.com"], check=True,
        capture_output=True, timeout=15,
    )
    if len(result.stdout) > 4 * 1024 * 1024:
        raise ValueError("admission metadata too large")
    return json.loads(result.stdout, object_pairs_hook=_pairs)


def verify_evidence(policy: dict, pr: dict, reviews: list, checks: dict, tip: str) -> str:
    """Verify concrete review/check records; aggregate approval/status is never consulted."""
    if set(policy) != {"schema", "repository", "pull_request", "head_sha", "base_sha",
                       "reviewer_ids", "required_checks", "isolation", "checked_tree"}:
        raise ValueError("invalid admission descriptor")
    if (policy["schema"] != "merge-pr-admission/v1" or policy["head_sha"] != tip
            or re.fullmatch(r"[0-9a-f]{40}", tip) is None
            or re.fullmatch(r"[0-9a-f]{40}", policy["base_sha"]) is None
            or type(policy["pull_request"]) is not int or policy["pull_request"] < 1):
        raise ValueError("admission identity mismatch")
    if (pr["number"] != policy["pull_request"] or pr["head"]["sha"] != tip
            or pr["base"]["ref"] != "main" or pr["merged"] is not True
            or pr["base"]["repo"]["full_name"] != policy["repository"]
            or pr["head"]["repo"]["full_name"] != policy["repository"]):
        raise ValueError("exact-head merged PR required")
    isolation = policy["isolation"]
    if (set(isolation) != {"passed", "assessment_ref", "scope", "baseline_commit"}
            or isolation["passed"] is not True
            or not isinstance(isolation["assessment_ref"], str)
            or not isolation["assessment_ref"].strip()
            or isolation["scope"] != "authoritative_strategy_execution"
            or re.fullmatch(r"[0-9a-f]{40}", isolation["baseline_commit"]) is None):
        raise ValueError("trusted Task4 attestation required")
    allowed = policy["reviewer_ids"]
    if not allowed or any(type(i) is not int or i < 1 for i in allowed) or len(reviews) >= 100:
        raise ValueError("independent review required")
    latest = {}
    for review in sorted(reviews, key=lambda row: row["id"]):
        if review["state"] in {"APPROVED", "CHANGES_REQUESTED", "DISMISSED"}:
            latest[review["user"]["id"]] = review
    if (any(row["state"] == "CHANGES_REQUESTED" for row in latest.values())
            or not any(uid in allowed and uid != pr["user"]["id"]
                       and row["state"] == "APPROVED" and row["commit_id"] == tip
                       for uid, row in latest.items())):
        raise ValueError("independent review at head required")
    required = policy["required_checks"]
    checked = policy["checked_tree"]
    if (set(checked) != {"base_sha", "head_sha", "tree_sha", "check_run_ids"}
            or checked["base_sha"] != policy["base_sha"] or checked["head_sha"] != tip
            or re.fullmatch(r"[0-9a-f]{40}", checked["tree_sha"]) is None
            or set(checked["check_run_ids"]) != set(required)):
        raise ValueError("trusted integrated checked-tree attestation required")
    if (not isinstance(required, dict) or not required
            or any(not isinstance(n, str) or not n or type(a) is not int or a < 1
                   for n, a in required.items())
            or checks["total_count"] != len(checks["check_runs"])
            or len(checks["check_runs"]) > 100):
        raise ValueError("named check records required")
    for name, app in required.items():
        runs = [r for r in checks["check_runs"] if r["name"] == name and r["app"]["id"] == app]
        if not runs:
            raise ValueError("required check missing")
        run = max(runs, key=lambda row: row["id"])
        if (run["id"] != checked["check_run_ids"][name] or run["head_sha"] != tip
                or run["status"] != "completed" or run["conclusion"] != "success"):
            raise ValueError("required check not green at head")
    merge = pr["merge_commit_sha"]
    if not isinstance(merge, str) or re.fullmatch(r"[0-9a-f]{40}", merge) is None:
        raise ValueError("verified merge commit required")
    return merge


def require_live_content(git: GitOps, tip: str, base: str) -> None:
    """Compare effective blobs, including deletions, before authority effects."""
    git.fetch_remote("main")
    remote = "refs/remotes/origin/main"
    if git.resolve("main") != git.remote_tip("main"):
        raise AdmissionPending("main changed after PR admission")
    for entry in git.changed_entries(git.merge_base(base, tip), tip):
        wanted = git.tree_blobs(tip, [entry.new_path]).get(entry.new_path)
        if git.blob_at(remote, entry.new_path) != wanted:
            raise AdmissionPending("admitted PR content is no longer present")


def verify_and_adopt(git: GitOps, tip: str, codeowners_text: str, *,
                     adopt: bool = True) -> tuple[int, str, str] | None:
    """All refusals are operational pending; no source import, gate or remote write occurs."""
    try:
        if re.fullmatch(r"[0-9a-f]{40}", tip) is None:
            return None
        policy = _descriptor()
        repo, number = policy["repository"], policy["pull_request"]
        if not isinstance(repo, str) or re.fullmatch(r"[\w.-]+/[\w.-]+", repo) is None:
            return None
        if type(number) is not int or number < 1:
            return None
        pr = _api(repo, f"pulls/{number}")
        reviews = _api(repo, f"pulls/{number}/reviews?per_page=100")
        checks = _api(repo, f"commits/{tip}/check-runs?per_page=100")
        merge = verify_evidence(policy, pr, reviews, checks, tip)
        base = policy["base_sha"]
        git.fetch_remote("main")
        if (not git.is_merge_of(merge, tip) or git.resolve(f"{merge}^1") != base
                or git.resolve(f"{merge}^{{tree}}") != policy["checked_tree"]["tree_sha"]
                or not git.is_ancestor(merge, "refs/remotes/origin/main")):
            return None
        entries = git.changed_entries(git.merge_base(base, tip), tip)
        if not evaluate_diff(entries, codeowners_text=codeowners_text).ok:
            return None
        attested = policy["isolation"]["baseline_commit"]
        remote = "refs/remotes/origin/main"
        if (not git.is_ancestor(attested, remote)
                or not evaluate_diff(git.changed_entries(attested, git.remote_tip("main")),
                                     codeowners_text=codeowners_text).ok):
            return None
        paths = [entry.new_path for entry in entries if not entry.change_type.startswith("D")]
        if any(git.blob_at(remote, p) != blob for p, blob in git.tree_blobs(tip, paths).items()):
            return None
        if adopt:
            git.adopt_verified_main(merge)
        require_live_content(git, tip, base)
        return number, merge, base
    except (OSError, ValueError, TypeError, KeyError, AttributeError, IndexError,
            AdmissionPending, subprocess.SubprocessError):
        return None
